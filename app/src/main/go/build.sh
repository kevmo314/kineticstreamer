#!/bin/bash
# Build the native libraries for the Android ABIs in $NATIVE_ABIS (default: all
# four, space separated). Runs on Linux, macOS and Windows (Git Bash).
#
#   build.sh deps  third-party C deps (libusb, OpenSSL, SRT, librist) via
#                  third_party/CMakeLists.txt -> third_party/output/<abi>/
#   build.sh jni   libkinetic.so via `go build -buildmode=c-shared`, copied to
#                  ../jniLibs/<abi>/ together with the third-party .so's
#
# Gradle runs both (see app/build.gradle.kts). `deps` skips ABIs already built from
# the current CMakeLists.txt (delete third_party/output to force a rebuild).

set -eo pipefail

STEP=$1
case "$STEP" in
    deps|jni) ;;
    *) echo "Usage: $0 deps|jni"; exit 1 ;;
esac

# `pwd -W` yields a C:/-style path under Git Bash, which native tools (cmake, go) understand.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && { pwd -W 2>/dev/null || pwd; })"
THIRD_PARTY_DIR="$SCRIPT_DIR/third_party/output"
JNI_LIBS_DIR="$SCRIPT_DIR/../jniLibs"
INCLUDE_DIR="$SCRIPT_DIR/include"
ANDROID_API=24 # keep in sync with third_party/CMakeLists.txt
read -r -a ABIS <<< "${NATIVE_ABIS:-arm64-v8a armeabi-v7a x86 x86_64}"

case "$OSTYPE" in
    linux*)             NDK_HOST_TAG="linux-x86_64" ;;
    darwin*)            NDK_HOST_TAG="darwin-x86_64" ;;
    msys*|cygwin*|win*) NDK_HOST_TAG="windows-x86_64" ;;
    *) echo "Unsupported host: $OSTYPE"; exit 1 ;;
esac

# Resolve ANDROID_NDK from the environment, else the newest NDK in ANDROID_HOME / local.properties.
if [ -z "$ANDROID_NDK" ]; then
    if [ -z "$ANDROID_HOME" ] && [ -f "$SCRIPT_DIR/../../../../local.properties" ]; then
        ANDROID_HOME=$(grep '^sdk.dir=' "$SCRIPT_DIR/../../../../local.properties" | cut -d= -f2-)
    fi
    if [ ! -d "$ANDROID_HOME/ndk" ]; then
        echo "ANDROID_NDK not set and could not be derived from ANDROID_HOME / local.properties"
        exit 1
    fi
    ANDROID_NDK="$ANDROID_HOME/ndk/$(ls "$ANDROID_HOME/ndk" | sort -V | tail -1)"
fi
NDK_BIN="$ANDROID_NDK/toolchains/llvm/prebuilt/$NDK_HOST_TAG/bin"
echo "Using ANDROID_NDK=$ANDROID_NDK for ABIs: ${ABIS[*]}"

# Run "$@" for every ABI in parallel, prefixing output with the ABI name.
for_each_abi() {
    local pids=() failed=0 abi
    for abi in "${ABIS[@]}"; do
        { "$@" "$abi" 2>&1 | sed -u "s/^/[$abi] /"; exit "${PIPESTATUS[0]}"; } &
        pids+=($!)
    done
    for pid in "${pids[@]}"; do wait "$pid" || failed=1; done
    return $failed
}

build_deps() {
    local abi=$1 build="third_party/build/$1" out="third_party/output/$1"
    # Skip ABIs already built from this CMakeLists.txt (e.g. restored from the CI cache).
    local stamp
    stamp=$(cksum < third_party/CMakeLists.txt)
    if [ "$(cat "$out/.stamp" 2>/dev/null)" = "$stamp" ]; then
        echo "up to date"
        return
    fi
    rm -rf "$build" "$out"
    cmake -S third_party -B "$build" -GNinja -Wno-dev \
          -DCMAKE_TOOLCHAIN_FILE="$ANDROID_NDK/build/cmake/android.toolchain.cmake" \
          -DANDROID_ABI="$abi" \
          -DANDROID_NDK="$ANDROID_NDK" \
          -DCMAKE_INSTALL_PREFIX="$THIRD_PARTY_DIR/$abi"
    cmake --build "$build"
    rm -rf "$build"
    echo "$stamp" > "$out/.stamp"
}

build_jni() {
    local abi=$1 goarch goarm cc
    case "$abi" in
        arm64-v8a)   goarch=arm64; cc=aarch64-linux-android ;;
        armeabi-v7a) goarch=arm;   cc=armv7a-linux-androideabi; goarm=7 ;;
        x86)         goarch=386;   cc=i686-linux-android ;;
        x86_64)      goarch=amd64; cc=x86_64-linux-android ;;
    esac
    local tp="$THIRD_PARTY_DIR/$abi" out="$JNI_LIBS_DIR/$abi"
    mkdir -p "$out"

    GOOS=android GOARCH="$goarch" GOARM="$goarm" CGO_ENABLED=1 \
        CC="$NDK_BIN/${cc}${ANDROID_API}-clang" \
        CXX="$NDK_BIN/${cc}${ANDROID_API}-clang++" \
        CGO_CFLAGS="-I$INCLUDE_DIR -I$tp/include -D__ANDROID__" \
        CGO_LDFLAGS="-L$tp/lib -lusb-1.0 -lsrt -lrist -ldl -static-libstdc++" \
        go build -C "$SCRIPT_DIR/cmd/jni" -buildmode=c-shared \
            -ldflags="-s -w -checklinkname=0 -extldflags '-Wl,-soname,libkinetic.so -Wl,-z,max-page-size=16384'" \
            -o "$out/libkinetic.so" \
            .
    cp "$tp/lib/libusb-1.0.so" "$tp/lib/libsrt.so" "$tp/lib/librist.so" "$out/"
}

cd "$SCRIPT_DIR"
if [ "$STEP" = deps ]; then
    # Each ABI is a separate cmake build, so they can run side by side.
    for_each_abi build_deps
else
    rm -rf "$JNI_LIBS_DIR" # so ABIs not selected this time cannot end up in the APK
    for_each_abi build_jni
    # Generated by `go build -buildmode=c-shared`; not used.
    rm -f cmd/jni/libkinetic.h
fi
